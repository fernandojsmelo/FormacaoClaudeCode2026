# int não tem limite de tamanho
print(2 ** 100)

# float é aproximado: alguns decimais não são exatos
print(0.1 + 0.2)
print(round(0.1 + 0.2, 2))

# Divisão com / sempre dá float, mesmo quando é exata
print(10 / 2)
print(type(10 / 2))

# Separador de milhar com _ (só para leitura)
populacao = 203_080_756
print(populacao)
