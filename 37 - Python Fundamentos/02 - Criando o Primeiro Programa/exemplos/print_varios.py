# Vários valores no mesmo print: o Python separa com espaço
print("Nome:", "Ana", "| Idade:", 29)

# sep: o que vai entre os valores
# end: o que vai no final (padrão: quebra de linha)
print("2026", "10", "05", sep="-")
print("Carregando", end="...")
print(" pronto!")

# Números e contas também podem ser impressos
print(2 + 3)
print("2 + 3")
