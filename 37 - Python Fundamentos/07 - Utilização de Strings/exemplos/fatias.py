palavra = "Python"
print(palavra[0:2])    # Py   (do 0 até antes do 2)
print(palavra[2:])     # thon (do 2 até o fim)
print(palavra[:4])     # Pyth (do começo até antes do 4)
print(palavra[::2])    # Pto  (de 2 em 2)
print(palavra[::-1])   # nohtyP (invertida)
print(palavra[1:100])  # ython (fatia não dá erro)
